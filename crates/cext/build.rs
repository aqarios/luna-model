//! Generates the C headers for the LunaModel C API into `include/luna_model/`.
//!
//! - `types.h`, `funcs.h`: produced by cbindgen, split via `item_types`.
//! - `funcs_py.h`: produced here by parsing the `LunaModelCApi` struct in
//!   `src/capi_table.rs` with `syn` and emitting one dispatch macro per field.
//!
//! The hand-written umbrella `include/luna_model.h` and `include/luna_model/{version,
//! attributes}.h` are NOT generated.

use std::path::{Path, PathBuf};

fn main() {
    let crate_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = crate_dir.join("include").join("luna_model");

    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=cbindgen.types.toml");
    println!("cargo:rerun-if-changed=cbindgen.funcs.toml");
    println!("cargo:rerun-if-changed=../capi/src/*.rs");

    std::fs::create_dir_all(&out_dir).expect("create include/luna_model");

    cbindgen_header(&crate_dir, "cbindgen.types.toml", &out_dir.join("types.h"));
    cbindgen_header(&crate_dir, "cbindgen.funcs.toml", &out_dir.join("funcs.h"));
    generate_funcs_py(&crate_dir, &out_dir.join("funcs_py.h"));
    generate_version(&out_dir.join("version.h"));
}

/// Runs cbindgen with `config_file` and writes the result to `out`.
fn cbindgen_header(crate_dir: &Path, config_file: &str, out: &Path) {
    let config = cbindgen::Config::from_file(crate_dir.join(config_file))
        .unwrap_or_else(|e| panic!("read {config_file}: {e}"));
    match cbindgen::Builder::new()
        .with_crate(crate_dir)
        .with_config(config)
        .generate()
    {
        Ok(bindings) => {
            bindings.write_to_file(out);
        }
        Err(err) => println!("cargo:warning=cbindgen failed for {}: {err}", out.display()),
    }
}

/// Parses the `LunaModelCApi` struct and emits the extension-mode dispatch header.
fn generate_funcs_py(crate_dir: &Path, out: &Path) {
    let path = crate_dir.join("../capi/src/vtable.rs");
    let source =
        std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let ast = syn::parse_file(&source).expect("parse capi_table.rs");

    let mut fields = Vec::new();
    for item in &ast.items {
        if let syn::Item::Struct(s) = item
            && s.ident == "LunaModelCApi"
        {
            for field in &s.fields {
                if let Some(ident) = &field.ident {
                    let name = ident.to_string();
                    if name != "abi_version" {
                        fields.push(name);
                    }
                }
            }
        }
    }
    assert!(
        !fields.is_empty(),
        "no fields found on LunaModelCApi (renamed/moved?)"
    );

    let mut text = String::from(FUNCS_PY_PRELUDE);
    text.push_str("\n/* Dispatch macros (one per LunaModelCApi field, generated): */\n");
    for field in &fields {
        text.push_str(&format!(
            "#define lm_{field}(...) (lunamodel__vtable->{field}(__VA_ARGS__))\n"
        ));
    }
    text.push_str(FUNCS_PY_EPILOGUE);

    std::fs::write(out, text).expect("write funcs_py.h");
}

/// Emits `version.h` with version macros parsed from `CARGO_PKG_VERSION`.
fn generate_version(out: &Path) {
    let version = std::env::var("CARGO_PKG_VERSION").expect("CARGO_PKG_VERSION");
    let core = version.split(['-', '+']).next().unwrap_or(&version);
    let mut parts = core.split('.');
    let major: u32 = parts.next().and_then(|s| s.parse().ok()).unwrap_or(0);
    let minor: u32 = parts.next().and_then(|s| s.parse().ok()).unwrap_or(0);
    let patch: u32 = parts.next().and_then(|s| s.parse().ok()).unwrap_or(0);

    let text = format!(
        r#"/* AUTO-GENERATED by crates/cext/build.rs from CARGO_PKG_VERSION. Do not edit. */
  #ifndef LUNA_MODEL_VERSION_H
  #define LUNA_MODEL_VERSION_H

  #define LUNA_MODEL_VERSION_MAJOR {major}
  #define LUNA_MODEL_VERSION_MINOR {minor}
  #define LUNA_MODEL_VERSION_PATCH {patch}
  #define LUNA_MODEL_VERSION "{version}"

  /* Packed 0xMMmmpp. */
  #define LUNA_MODEL_VERSION_HEX                          \
      ((((LUNA_MODEL_VERSION_MAJOR) & 0xff) << 16) |      \
       (((LUNA_MODEL_VERSION_MINOR) & 0xff) << 8) |       \
       (((LUNA_MODEL_VERSION_PATCH) & 0xff)))

  #endif /* LUNA_MODEL_VERSION_H */
  "#
    );
    std::fs::write(out, text).expect("write version.h");
}

const FUNCS_PY_PRELUDE: &str = r#"/* AUTO-GENERATED by crates/cext/build.rs from the LunaModelCApi struct. Do not edit. */
#ifndef LUNA_MODEL_FUNCS_PY_H
#define LUNA_MODEL_FUNCS_PY_H

/*
 * Extension-mode entry points. The umbrella `luna_model.h` includes this file
 * (instead of `funcs.h`) when LUNA_MODEL_PYTHON_EXTENSION is defined. Rather than
 * linking the lm_* symbols, each lm_* call dispatches through the C API table
 * imported from the `luna_model` wheel's `_C_API` PyCapsule. Requires <Python.h>,
 * which the umbrella includes first.
 */

#include "luna_model/types.h"

#ifdef __cplusplus
extern "C" {
#endif

#define LUNA_MODEL_CAPI_CAPSULE_NAME "luna_model._lm._C_API"

/* The imported C API table; NULL until import_luna_model() succeeds. Each TU that
 * includes this header has its own pointer; call import_luna_model() once per TU. */
static const LunaModelCApi *lunamodel__vtable = NULL;

/* Returns the imported table, or NULL if import_luna_model() has not succeeded. */
static inline const LunaModelCApi *lunamodel_api(void) { return lunamodel__vtable; }

/* Imports `luna_model._lm` and binds its `_C_API` capsule. Returns 0 on success,
 * -1 on failure (Python exception set). Call once during module init. */
static inline int import_luna_model(void) {
    PyObject *module = PyImport_ImportModule("luna_model._lm");
    if (module == NULL) {
        return -1;
    }
    PyObject *capsule = PyObject_GetAttrString(module, "_C_API");
    Py_DECREF(module);
    if (capsule == NULL) {
        return -1;
    }
    void *pointer = PyCapsule_GetPointer(capsule, LUNA_MODEL_CAPI_CAPSULE_NAME);
    Py_DECREF(capsule);
    if (pointer == NULL) {
        return -1;
    }
    const LunaModelCApi *api = (const LunaModelCApi *)pointer;
    if (api->abi_version != LUNA_MODEL_CAPI_ABI_VERSION) {
        PyErr_Format(PyExc_ImportError,
                     "luna_model C API ABI mismatch: built against %d, runtime %u",
                     (int)LUNA_MODEL_CAPI_ABI_VERSION, api->abi_version);
        return -1;
    }
    lunamodel__vtable = api;
    return 0;
}
"#;

const FUNCS_PY_EPILOGUE: &str = r#"
#ifdef __cplusplus
} /* extern "C" */
#endif

#endif /* LUNA_MODEL_FUNCS_PY_H */
"#;
